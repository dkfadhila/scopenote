const {chromium}=require('playwright');
const fs=require('node:fs/promises');
const assert=require('node:assert/strict');
(async()=>{
  await fs.mkdir('artifacts',{recursive:true});
  const browser=await chromium.launch({...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE?{executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE}:{}),headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1100},deviceScaleFactor:1});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:5178/');await page.evaluate(()=>document.fonts.ready);
  await page.getByRole('heading',{name:'Scope builder',exact:true}).waitFor();
  await page.screenshot({path:'artifacts/desktop.png',fullPage:true,animations:'disabled'});
  await page.getByRole('tab',{name:'Questions (3)'}).click();
  await page.getByRole('heading',{name:'A few things to ask.'}).waitFor();
  await page.getByRole('checkbox').first().check();assert(await page.getByRole('checkbox').first().isChecked());
  await page.getByRole('tab',{name:'Scope of work'}).click();
  await page.getByLabel('Hours for Discovery & visual direction').fill('7');
  await page.getByLabel('Hourly rate',{exact:true}).fill('100');
  await page.getByLabel('Contingency percentage').fill('10');
  await page.getByLabel('Currency',{exact:true}).selectOption('EUR');
  assert((await page.locator('.estimate-total').innerText()).includes('4,840'));
  await page.getByRole('button',{name:'Save draft',exact:true}).click();
  await page.getByRole('button',{name:/Saved drafts/}).click();
  await page.getByRole('button',{name:'Open draft'}).click();
  assert.equal(await page.getByLabel('Hourly rate',{exact:true}).inputValue(),'100');
  await page.reload();
  await page.getByRole('button',{name:/Saved drafts/}).click();
  assert.equal(await page.getByRole('button',{name:'Open draft'}).count(),1);
  await page.getByRole('button',{name:'Open draft'}).click();
  await page.getByRole('tab',{name:'Proposal preview'}).click();
  const download=page.waitForEvent('download');await page.getByRole('button',{name:'Export proposal'}).click();
  const file=await download;await file.saveAs('artifacts/exported-proposal.md');
  const proposal=await fs.readFile('artifacts/exported-proposal.md','utf8');
  assert(proposal.includes('EUR 100/hour'));assert(proposal.includes('Outside this scope'));
  await page.getByRole('button',{name:'New project',exact:true}).click();
  await page.getByRole('dialog').getByLabel('Client name').fill('Ruang Coffee');
  await page.getByRole('dialog').getByLabel('Project name').fill('Seasonal menu website');
  await page.getByRole('dialog').getByRole('button',{name:'Create project',exact:true}).click();
  await page.getByRole('heading',{name:'A blank page, in a good way.'}).waitFor();
  await page.getByRole('button',{name:'Shape this into a scope'}).click();
  assert((await page.getByRole('alert').innerText()).includes('30 characters'));
  await page.getByLabel('What did they have in mind?').fill('We need a cafe menu website with a contact page and opening hours.');
  await page.getByRole('button',{name:'Shape this into a scope'}).click();
  await page.getByRole('heading',{name:'Workspace connections'}).waitFor();
  await page.getByRole('button',{name:'Close settings'}).click();
  await page.getByRole('button',{name:/Try an example/}).click();
  for(const width of [390,768,1024,1440]) {
    await page.setViewportSize({width,height:1000});
    await page.screenshot({path:`artifacts/viewport-${width}.png`,fullPage:true,animations:'disabled'});
    const sizes=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth}));
    assert(sizes.scroll<=sizes.width,`Horizontal overflow at ${width}: ${sizes.scroll}`);
  }
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.reload();await page.getByRole('heading',{name:'Your working scope'}).waitFor();
  assert.deepEqual(errors,[]);
  await browser.close();console.log('PASS: desktop/mobile, no horizontal overflow, tabs, checkbox, estimate, save/reload, new project, empty/validation states, model dialog, export and reduced motion.');
})().catch(e=>{console.error(e);process.exit(1);});
